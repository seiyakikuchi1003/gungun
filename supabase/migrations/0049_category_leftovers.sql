-- ============================================================================
-- 0049_category_leftovers.sql — Click の10区分から外れた商品を寄せ直す
--
-- 0045 で既存データを Click の10区分に寄せたが、そのあと（0045 を本番に当てる前に）
-- 水やりから出品された商品が1件、旧カテゴリー「バッグ・小物」で入っていた。
-- 原因は水やり画面の初期値が旧カテゴリーのままだったこと（アプリ側で修正済み）。
--
-- 同じ取りこぼしが今後も起きないよう、10区分に無いものはまとめて寄せる。
-- 名指しの対応表ではなく「一覧に無いもの」で拾うので、表記ゆれにも効く。
-- ============================================================================

-- バッグ・小物などの服飾小物はアクセサリー側へ
update items set category = 'ファッション・アクセサリー'
where category in ('バッグ・小物', 'メンズ', 'レディース', 'ファッション');

-- それ以外で10区分に無いものは、いちばん広い区分に寄せる
update items set category = '日用品・雑貨・文具'
where category is null
   or btrim(category) = ''
   or category not in (
     '本・漫画・CD・DVD',
     'ファッション・アクセサリー',
     '趣味・サブカル',
     'コスメ・美容',
     'ベビー・キッズ用品',
     '家電・デジタルガジェット',
     '日用品・雑貨・文具',
     '食品（常温のみ）',
     'スポーツ用品',
     'アウトドア・旅行品'
   );
