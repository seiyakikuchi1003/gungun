-- ============================================================================
-- 0032_image_size_limit.sql — 写真が「容量が多くて投稿できません」になる（項目3）
--
-- item-images / avatars の1ファイル上限が 5MB だった。
-- 最近の端末で撮った写真は、圧縮をかけても 5MB を超えることがあり、
-- 「10枚まで出せる」はずが1〜数枚で弾かれていた。
--
-- 上限を 15MB に引き上げる。アプリ側でも撮影・選択時に圧縮しているので、
-- 通常はここに当たらない。当たるのは無圧縮の高解像度写真だけ。
-- ============================================================================

update storage.buckets set file_size_limit = 15728640
 where id in ('item-images', 'avatars');
