-- ============================================================================
-- 0024_item_comment_type.sql — 商品コメントを掲示板から切り離す（2026-08-12 指摘）
--
-- 【何が起きていたか】
-- 商品へのコメント通知を 'board_comment' 型で入れていたため、
--   ・通知設定の「掲示板コメント」を切ると商品コメントまで止まる
--   ・通知をタップすると /board/<商品ID> に飛び、掲示板に無い投稿を開いて真っ白
-- という2つの不具合になっていた。型を分けて両方まとめて直す。
--
-- enum への値追加は、同じトランザクションの中では使えない。
-- なので「値を足すだけ」のこのファイルと、使う 0025 を分けている。
-- ============================================================================

alter type notification_type add value if not exists 'item_comment';
